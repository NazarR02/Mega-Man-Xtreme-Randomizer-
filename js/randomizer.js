function buildSettings({
  baseSeed,
  options,
  paletteValues,
  palettePresetKey = "custom",
  weaponPaletteValues = {},
  startingGear,
  fromSeed = false,
}) {
  const normalizedBaseSeed = validateBaseSeed(baseSeed);
  const normalizedOptions = normalizeOptions(options);
  const normalizedPalette = normalizePaletteValues(paletteValues);
  const normalizedPreset = String(palettePresetKey ?? "custom").trim() || "custom";
  const normalizedWeaponPalettes = normalizeWeaponPalettes(
    Object.keys(weaponPaletteValues ?? {}).length > 0 ? weaponPaletteValues : defaultWeaponPaletteValues(),
  );
  const normalizedStartingGear = normalizeStartingGear(startingGear);
  const seedName = createSeedName(normalizedBaseSeed);
  const payload = {
    v: 2,
    s: normalizedBaseSeed,
    o: packOptions(normalizedOptions),
    p: paletteValuesToHex(normalizedPalette),
    k: normalizedPreset,
    w: weaponPalettesToPayload(normalizedWeaponPalettes),
    g: packStartingGear(normalizedStartingGear),
  };
  const seedSlug = seedName.replace(/\s+/g, "-");

  return {
    encodedSeed: `${SEED_PREFIX_V2}${seedSlug}-${stringToHex(JSON.stringify(payload))}`,
    seedName,
    baseSeed: normalizedBaseSeed,
    options: normalizedOptions,
    paletteValues: normalizedPalette,
    palettePresetKey: normalizedPreset,
    weaponPaletteValues: normalizedWeaponPalettes,
    startingGear: normalizedStartingGear,
    fromSeed,
  };
}

function buildPlan(options, rng, startingRewards, baseSeed) {
  const locationRewards = new Map();
  const bossRewards = new Map();
  const domeWeapon = createDomeWeapon(baseSeed);
  const allLocations = getAllLocations().map(location => ({ ...location,
    requirements: getLocationRequirements(location, { domeWeapon }) }));
  const itemLocations = allLocations.filter((location) => location.group === "item");
  const armorLocations = allLocations.filter((location) => location.group === "armor");
  const itemPoolExtras = options.randomizeItems && shouldIncludeExtraItemRewards(baseSeed)
    ? EXTRA_ITEM_REWARDS.filter((reward) => !isRewardCoveredByStart(reward, startingRewards))
    : [];
  const reservedRewards = [
    ...allLocations.map((location) => location.vanillaReward),
    ...BOSS_WEAPONS,
    ...itemPoolExtras,
  ].filter((reward) => !isRewardCoveredByStart(reward, startingRewards));
  const allocateFiller = createFillerAllocator(rng, reservedRewards, startingRewards);

  if (options.randomizeBossRewards) {
    const generalLocations = [];

    if (options.randomizeItems) generalLocations.push(...itemLocations);
    else assignLocationGroup(itemLocations, false, rng, locationRewards, startingRewards, allocateFiller);

    if (options.randomizeCapsules) generalLocations.push(...armorLocations);
    else assignLocationGroup(armorLocations, false, rng, locationRewards, startingRewards, allocateFiller);

    const targets = [
      ...generalLocations.map((location) => ({ kind: "location", location })),
      ...STAGES.map((stage) => ({ kind: "boss", stage })),
    ];
    let pool = [
      ...generalLocations.map((location) => cloneReward(location.vanillaReward)),
      ...BOSS_WEAPONS.map(cloneReward),
      ...itemPoolExtras.map(cloneReward),
    ].filter((reward) => !isRewardCoveredByStart(reward, startingRewards));
    pool = shuffle(fillRewardPool(pool, targets.length, allocateFiller), rng);
    ensureRequiredRewardsSelected(pool, targets.length, itemPoolExtras);

    targets.forEach((target, index) => {
      const reward = cloneReward(pool[index]);
      if (target.kind === "location") locationRewards.set(target.location.id, [reward]);
      else bossRewards.set(target.stage.id, [reward]);
    });
  } else {
    assignLocationGroup(itemLocations, options.randomizeItems, rng, locationRewards, startingRewards, allocateFiller, itemPoolExtras);
    assignLocationGroup(armorLocations, options.randomizeCapsules, rng, locationRewards, startingRewards, allocateFiller);

    let bossWeaponPool = BOSS_WEAPONS
      .filter((reward) => !isRewardCoveredByStart(reward, startingRewards))
      .map(cloneReward);
    bossWeaponPool = shuffle(fillBossWeaponPool(bossWeaponPool, STAGES.length), rng);
    STAGES.forEach((stage, index) => {
      const reward = bossWeaponPool[index];
      bossRewards.set(stage.id, reward ? [cloneReward(reward)] : []);
    });
  }

  placeProgressionExtras({ allLocations, locationRewards, options, rng, startingRewards });
  const stageTables = buildStageTables(locationRewards, bossRewards);
  enforceHeartTankLimit(stageTables);
  return { locationRewards, bossRewards, stageTables };
}

function assignLocationGroup(locations, shouldShuffle, rng, rewardMap, startingRewards, allocateFiller, requiredRewards = []) {
  if (!shouldShuffle) {
    for (const location of locations) {
      const reward = isRewardCoveredByStart(location.vanillaReward, startingRewards)
        ? allocateFiller()
        : cloneReward(location.vanillaReward);
      rewardMap.set(location.id, [reward]);
    }
    return;
  }

  let pool = locations
    .map((location) => cloneReward(location.vanillaReward))
    .concat(requiredRewards.map(cloneReward))
    .filter((reward) => !isRewardCoveredByStart(reward, startingRewards));
  pool = shuffle(fillRewardPool(pool, locations.length, allocateFiller), rng);
  ensureRequiredRewardsSelected(pool, locations.length, requiredRewards);
  locations.forEach((location, index) => rewardMap.set(location.id, [cloneReward(pool[index])]));
}

function ensureRequiredRewardsSelected(pool, selectedCount, requiredRewards) {
  if (selectedCount <= 0 || requiredRewards.length === 0) return pool;

  for (const requiredReward of requiredRewards) {
    const requiredKey = rewardKey(requiredReward);
    const currentIndex = pool.findIndex((reward) => rewardKey(reward) === requiredKey);
    if (currentIndex < 0 || currentIndex < selectedCount) continue;

    const replacementIndex = findRequiredRewardReplacementIndex(pool, selectedCount, requiredKey);
    [pool[replacementIndex], pool[currentIndex]] = [pool[currentIndex], pool[replacementIndex]];
  }

  return pool;
}

function findRequiredRewardReplacementIndex(pool, selectedCount, requiredKey) {
  for (let index = selectedCount - 1; index >= 0; index -= 1) {
    const reward = pool[index];
    if (rewardKey(reward) === requiredKey) return index;
    if (reward.type !== REWARD_TYPES.BOSS_WEAPON && reward.type !== REWARD_TYPES.SIGMA_KEY && reward.type !== REWARD_TYPES.BOSS_KEY) {
      return index;
    }
  }

  return selectedCount - 1;
}

function shouldIncludeExtraItemRewards(baseSeed) {
  return hashText(`${baseSeed}:extra-item-rewards`) % EXTRA_ITEM_REWARD_RATE === 0;
}

function fillRewardPool(pool, targetCount, allocateFiller) {
  const filled = [...pool];
  while (filled.length < targetCount) filled.push(allocateFiller());
  return filled;
}

function fillBossWeaponPool(pool, targetCount) {
  const filled = [...pool];
  if (pool.length === 0) return filled;
  let duplicateIndex = 0;
  while (filled.length < targetCount) {
    filled.push(cloneReward(pool[duplicateIndex % pool.length]));
    duplicateIndex += 1;
  }
  return filled;
}

function createFillerAllocator(rng, reservedRewards, startingRewards) {
  const trackedRewards = [...reservedRewards, ...startingRewards].map(cloneReward);
  return function allocateFiller() {
    const reward = createFillerReward(rng, trackedRewards, startingRewards);
    trackedRewards.push(cloneReward(reward));
    return reward;
  };
}

function placeProgressionExtras({ allLocations, locationRewards, options, rng, startingRewards }) {
  const bossKeys = options.lockBossAccess
    ? shuffle(getBossKeys().filter((reward) => !isRewardCoveredByStart(reward, startingRewards)), rng)
    : [];
  const sigmaKeys = shuffle(
    SIGMA_KEYS.filter((reward) => !isRewardCoveredByStart(reward, startingRewards)).map(cloneReward),
    rng,
  );
  const balancedTargets = createBalancedLocationTargets(allLocations, rng);
  const sigmaTargets = createSigmaLocationTargets(allLocations, startingRewards, rng, options);
  const usedTargets = new Set();

  const appendRewards = (rewards, preferredTargets) => {
    for (const reward of rewards) {
      const target = preferredTargets.find((location) => !usedTargets.has(location.id)) ??
        balancedTargets.find((location) => !usedTargets.has(location.id));
      if (!target) throw new Error("There are not enough locations to place progression.");
      locationRewards.get(target.id).push(cloneReward(reward));
      usedTargets.add(target.id);
    }
  };

  appendRewards(sigmaKeys, sigmaTargets);
  appendRewards(bossKeys, balancedTargets);
}

function createSigmaLocationTargets(allLocations, startingRewards, rng, options) {
  if (options.requireFullProgression) {
    return createFullProgressionSigmaTargets(allLocations, startingRewards, rng);
  }

  return createWeightedLocationOrder(allLocations, (location) =>
    getSigmaTargetWeight(location, startingRewards, false),
    rng,
  );
}

function createFullProgressionSigmaTargets(allLocations, startingRewards, rng) {
  const earlyTargets = allLocations.filter((location) => location.requirements.length === 0);
  const deepTargets = allLocations.filter((location) => location.requirements.length > 0);
  const ordered = [];
  const earlyTarget = pickWeightedLocation(earlyTargets, (location) =>
    getSigmaTargetWeight(location, startingRewards, true),
    rng,
  );
  const deepTarget = pickWeightedLocation(deepTargets, (location) =>
    getSigmaTargetWeight(location, startingRewards, true),
    rng,
  );

  if (earlyTarget) ordered.push(earlyTarget);
  if (deepTarget && !ordered.some((location) => location.id === deepTarget.id)) ordered.push(deepTarget);

  const used = new Set(ordered.map((location) => location.id));
  const remainingTargets = createWeightedLocationOrder(allLocations, (location) =>
    getSigmaTargetWeight(location, startingRewards, true),
    rng,
  );
  for (const location of remainingTargets) {
    if (used.has(location.id)) continue;
    ordered.push(location);
    used.add(location.id);
  }

  return ordered;
}

function createWeightedLocationOrder(locations, getWeight, rng) {
  const remaining = [...locations];
  const ordered = [];

  while (remaining.length > 0) {
    const picked = pickWeightedLocation(remaining, getWeight, rng);
    if (!picked) break;
    ordered.push(picked);
    remaining.splice(remaining.findIndex((location) => location.id === picked.id), 1);
  }

  return ordered;
}

function pickWeightedLocation(locations, getWeight, rng) {
  if (locations.length === 0) return null;
  const weightedLocations = locations.map((location) => ({
    location,
    weight: Math.max(1, Number(getWeight(location)) || 1),
  }));
  const totalWeight = weightedLocations.reduce((total, entry) => total + entry.weight, 0);
  let roll = rng() * totalWeight;

  for (const entry of weightedLocations) {
    roll -= entry.weight;
    if (roll <= 0) return entry.location;
  }

  return weightedLocations[weightedLocations.length - 1].location;
}

function getSigmaTargetWeight(location, startingRewards, requireFullProgression) {
  let weight = 8;
  if (location.requirements.length === 0) weight += requireFullProgression ? 2 : 4;
  else weight += 7 + (location.requirements.length * 3);

  if (isLocationDelayedByStartingRewards(location, startingRewards)) weight += requireFullProgression ? 5 : 3;
  if (location.requirements.some((requirement) => requirement.kind === "weapon")) weight += 3;
  if (location.requirements.some((requirement) => requirement.kind === "armor")) weight += 3;
  if (
    location.requirements.some((requirement) => requirement.kind === "weapon") &&
    location.requirements.some((requirement) => requirement.kind === "armor")
  ) {
    weight += 2;
  }

  return weight;
}

function isLocationDelayedByStartingRewards(location, startingRewards) {
  return location.requirements.length > 0 &&
    !location.requirements.every((requirement) => isRequirementCoveredByStart(requirement, startingRewards));
}

function isRequirementCoveredByStart(requirement, startingRewards) {
  if (requirement.kind === "armor") {
    return isRewardCoveredByStart({ type: REWARD_TYPES.ARMOR_PART, value: requirement.value }, startingRewards);
  }

  if (requirement.kind === "weapon") {
    return isRewardCoveredByStart({ type: REWARD_TYPES.BOSS_WEAPON, value: requirement.value }, startingRewards);
  }

  return false;
}

function createBalancedLocationTargets(locations, rng) {
  const stageIds = shuffle([...new Set(locations.map((location) => location.stageId))], rng);
  const buckets = stageIds.map((stageId) =>
    shuffle(locations.filter((location) => location.stageId === stageId), rng),
  );
  const ordered = [];
  let remaining = true;

  while (remaining) {
    remaining = false;
    for (const bucket of buckets) {
      if (bucket.length === 0) continue;
      ordered.push(bucket.shift());
      remaining = true;
    }
  }

  return ordered;
}

function enforceHeartTankLimit(stageTables) {
  const heartTankCount = stageTables.reduce(
    (total, stageTable) => total + stageTable.entries.reduce(
      (stageTotal, entry) => stageTotal + entry.rewards.filter(
        (reward) => reward.type === REWARD_TYPES.HEART_TANK,
      ).length,
      0,
    ),
    0,
  );

  if (heartTankCount > 8) {
    throw new Error(`The seed generated ${heartTankCount} Heart Tanks; the global maximum is 8.`);
  }
}

function buildStageTables(locationRewards, bossRewards) {
  return STAGES.map((stage) => ({
    stageId: stage.id,
    stageName: stage.name,
    entries: [
      ...stage.locations.map((location) => ({
        locationId: location.id,
        locationName: location.name,
        objectId: location.objectId,
        rewards: locationRewards.get(location.id) ?? [],
      })),
      {
        locationId: stage.boss.id,
        locationName: stage.boss.name,
        objectId: stage.boss.objectId,
        rewards: bossRewards.get(stage.id) ?? [],
      },
    ],
  }));
}

function selectBaseStartingRewards(startingGear, rng) {
  if (startingGear.mode === "none") return [];

  if (startingGear.mode === "custom") {
    return startingGear.selectedItemIds.map(findStartingRewardById).filter(Boolean);
  }

  const count = startingGear.mode === "generous" ? 4 : 2;
  if (startingGear.mode === "generous") {
    const priority = shuffle(getGenerousPriorityPool(), rng).slice(0, 2);
    const selected = new Set(priority.map(rewardKey));
    const rest = shuffle(getAutomaticStartingPool().filter((item) => !selected.has(rewardKey(item))), rng);
    return applyRareStartingRewards([...priority, ...rest.slice(0, count - priority.length)], count, rng);
  }

  return applyRareStartingRewards(shuffle(getAutomaticStartingPool(), rng).slice(0, count), count, rng);
}

function applyRareStartingRewards(rewards, slotCount, rng) {
  const selected = rewards.map(cloneReward);
  if (selected.length === 0) return selected;
  if (rng() >= slotCount / RARE_STARTING_REWARD_POOL_SIZE) return selected;
  if (selected.some((reward) => rewardKey(reward) === rewardKey(SHOTOKAN_REWARD))) return selected;

  const replaceIndex = Math.floor(rng() * selected.length);
  selected[replaceIndex] = cloneReward(SHOTOKAN_REWARD);
  return selected;
}

function selectRequiredStartingReward(blockingRewards, currentStartingRewards) {
  const currentKeys = new Set(currentStartingRewards.map(rewardKey));
  const candidates = blockingRewards
    .filter((reward) => !currentKeys.has(rewardKey(reward)) && !isRewardCoveredByStart(reward, currentStartingRewards))
    .sort((a, b) => rewardKey(a).localeCompare(rewardKey(b)));

  for (const candidate of candidates) {
    if (compressStartingRewards([...currentStartingRewards, candidate]).length <= STARTING_TABLE_MAX_ENTRIES) {
      return cloneReward(candidate);
    }
  }
  return null;
}

function validateCustomStartingCapacity(settings) {
  if (settings.startingGear.mode !== "custom") return;
  const rewards = settings.startingGear.selectedItemIds.map(findStartingRewardById).filter(Boolean);
  if (!settings.options.lockBossAccess) rewards.push(cloneReward(ALL_BOSS_KEYS_REWARD));
  const count = compressStartingRewards(rewards).length;
  if (count > STARTING_TABLE_MAX_ENTRIES) {
    throw new Error(`Custom Start uses ${count} entries; the patch allows ${STARTING_TABLE_MAX_ENTRIES}.`);
  }
}

function isRewardCoveredByStart(reward, startingRewards) {
  return startingRewards.some((starting) => {
    if (starting.type !== reward.type) return false;
    if (starting.value === reward.value) return true;
    if (starting.value === 0xff) return true;
    return starting.type === 0x07 && starting.value === 0x03 && (reward.value === 0x01 || reward.value === 0x02);
  });
}

function mergeRewards(...rewardGroups) {
  const merged = new Map();
  for (const reward of rewardGroups.flat()) merged.set(rewardKey(reward), cloneReward(reward));
  return [...merged.values()];
}

function countRandomizedLocations(plan) {
  let count = 0;
  for (const stage of STAGES) {
    for (const location of stage.locations) {
      if (!sameRewardList(plan.locationRewards.get(location.id) ?? [], [location.vanillaReward])) count += 1;
    }
    if (!sameRewardList(plan.bossRewards.get(stage.id) ?? [], [stage.boss.vanillaReward])) count += 1;
  }
  return count;
}

function getSigmaKeySeparation(plan, validation) {
  const sigmaSpheres = [];

  validation.spheres.forEach((sphere, sphereIndex) => {
    const sphereActions = new Set(sphere);

    for (const stage of STAGES) {
      for (const location of stage.locations) {
        if (!sphereActions.has(`${stage.name} - ${location.name}`)) continue;
        for (const reward of plan.locationRewards.get(location.id) ?? []) {
          if (isSigmaKeyReward(reward)) sigmaSpheres.push(sphereIndex + 1);
        }
      }

      if (!sphereActions.has(`${stage.name} - Boss`)) continue;
      for (const reward of plan.bossRewards.get(stage.id) ?? []) {
        if (isSigmaKeyReward(reward)) sigmaSpheres.push(sphereIndex + 1);
      }
    }
  });

  if (sigmaSpheres.length < 2) {
    return { distinct: true, hasMinimumGap: true, spheres: sigmaSpheres };
  }

  if (new Set(sigmaSpheres).size !== sigmaSpheres.length) {
    return { distinct: false, hasMinimumGap: false, spheres: sigmaSpheres };
  }

  const sortedSpheres = [...sigmaSpheres].sort((a, b) => a - b);
  const hasMinimumGap = sortedSpheres.every((sphere, index) =>
    index === 0 || sphere - sortedSpheres[index - 1] >= MIN_SIGMA_KEY_SPHERE_GAP
  );
  return { distinct: true, hasMinimumGap, spheres: sortedSpheres };
}

function isSigmaKeyReward(reward) {
  return reward.type === REWARD_TYPES.SIGMA_KEY;
}

function sameRewardList(a, b) {
  if (a.length !== b.length) return false;
  return a.every((reward, index) => reward.type === b[index].type && reward.value === b[index].value);
}

function shuffle(items, rng) {
  const copy = [...items];
  for (let index = copy.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(rng() * (index + 1));
    [copy[index], copy[swapIndex]] = [copy[swapIndex], copy[index]];
  }
  return copy;
}

function createRng(seed) {
  let hash = hashText(seed);
  return function rng() {
    hash += 0x6d2b79f5;
    let value = hash;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

function createSeedName(baseSeed) {
  const adjective = SEED_ADJECTIVES[hashText(`${baseSeed}:adjective`) % SEED_ADJECTIVES.length];
  const boss = SEED_BOSSES[hashText(`${baseSeed}:boss`) % SEED_BOSSES.length];
  return `${adjective} ${boss}`;
}

function hashText(value) {
  let hash = 2166136261;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function normalizeOptions(options = {}) {
  return {
    randomizeItems: Boolean(options.randomizeItems),
    randomizeCapsules: Boolean(options.randomizeCapsules),
    randomizeBossRewards: Boolean(options.randomizeBossRewards),
    lockBossAccess: Boolean(options.lockBossAccess),
    requireFullProgression: Boolean(options.requireFullProgression),
    showItemTexts: Boolean(options.showItemTexts),
    randomizeBossWeaknesses: Boolean(options.randomizeBossWeaknesses),
  };
}

function normalizeStartingGear(startingGear = {}) {
  const mode = STARTING_MODES.has(startingGear.mode) ? startingGear.mode : "normal";
  const ids = Array.isArray(startingGear.selectedItemIds) ? startingGear.selectedItemIds : [];
  const selectedItemIds = [...new Set(ids.map(String))].filter((id) => Boolean(findStartingRewardById(id)));
  return { mode, selectedItemIds: mode === "custom" ? selectedItemIds : [] };
}

function packOptions(options) {
  return (options.randomizeItems ? 1 : 0) |
    (options.randomizeCapsules ? 2 : 0) |
    (options.randomizeBossRewards ? 4 : 0) |
    (options.lockBossAccess ? 8 : 0) |
    (options.requireFullProgression ? 16 : 0) |
    (options.showItemTexts ? 32 : 0) |
    (options.randomizeBossWeaknesses ? 64 : 0);
}

function unpackOptions(flags) {
  const value = Number(flags);
  if (!Number.isInteger(value) || value < 0 || value > 127) throw new Error("Invalid seed: options are out of range.");
  return {
    randomizeItems: Boolean(value & 1),
    randomizeCapsules: Boolean(value & 2),
    randomizeBossRewards: Boolean(value & 4),
    lockBossAccess: Boolean(value & 8),
    requireFullProgression: Boolean(value & 16),
    showItemTexts: Boolean(value & 32),
    randomizeBossWeaknesses: Boolean(value & 64),
  };
}

function packStartingGear(startingGear) {
  return { m: startingGear.mode, i: startingGear.selectedItemIds };
}

function unpackStartingGear(payload) {
  return normalizeStartingGear({ mode: payload?.m, selectedItemIds: payload?.i });
}

function normalizePaletteValues(values) {
  if (!Array.isArray(values) || ![4, 8].includes(values.length)) throw new Error("Invalid seed: the palette must contain 8 bytes.");
  const expanded = values.length === 4 ? [0x73, 0x46, ...values, 0x42, 0x08] : values;
  return expanded.map((value) => {
    const byte = Number(value);
    if (!Number.isInteger(byte) || byte < 0 || byte > 0xff) throw new Error("Invalid seed: palette out of range.");
    return byte;
  });
}

function validateBaseSeed(value) {
  const seed = String(value ?? "").trim().toLowerCase();
  if (!/^[0-9a-f]{16}$/.test(seed)) throw new Error("Invalid seed: the RNG core must have 16 hexadecimal characters.");
  return seed;
}

function parseHexPayload(hex) {
  try {
    return JSON.parse(hexToString(hex));
  } catch {
    throw new Error("Invalid or corrupted seed. The package could not be read.");
  }
}

function paletteValuesToHex(values) {
  return values.map(formatHexByte).join("");
}

function shouldWriteRandomPalettes(palettePresetKey) {
  return palettePresetKey === "random_all" || palettePresetKey === "chaos_all";
}

function paletteHexToValues(hex) {
  const cleanHex = String(hex ?? "").trim();
  if (!/^(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{16})$/.test(cleanHex)) throw new Error("Invalid seed: the saved palette does not have 8 bytes.");
  const values = Array.from({ length: cleanHex.length / 2 }, (_, index) => Number.parseInt(cleanHex.slice(index * 2, index * 2 + 2), 16));
  return values.length === 4 ? [0x73, 0x46, ...values, 0x42, 0x08] : values;
}

function normalizeWeaponPalettes(palettes) {
  if (!palettes || typeof palettes !== "object") return {};
  const present = WEAPON_PALETTES.filter((entry) => Object.hasOwn(palettes, entry.id));
  if (present.length === 0) return {};
  if (present.length !== WEAPON_PALETTES.length) throw new Error("Invalid seed: weapon palettes are missing.");
  return Object.fromEntries(present.map((entry) => [entry.id, normalizePaletteValues(palettes[entry.id])]));
}

function defaultWeaponPaletteValues() {
  return Object.fromEntries(WEAPON_PALETTES.map((entry) => [entry.id, [...entry.defaultValues]]));
}

function weaponPalettesToPayload(palettes) {
  return Object.fromEntries(Object.entries(palettes).map(([id, values]) => [id, paletteValuesToHex(values)]));
}

function weaponPalettesFromPayload(payload) {
  if (!payload || typeof payload !== "object") return {};
  return Object.fromEntries(Object.entries(payload).map(([id, value]) => [id, paletteHexToValues(value)]));
}

function formatReward(reward) {
  return reward.label;
}

function formatRewardList(rewards) {
  return rewards.length ? rewards.map((reward) => reward.label).join(", ") : "None";
}

function formatStartingMode(mode) {
  if (mode === "none") return "No Starting Gear";
  return mode === "generous" ? "Generous Start" : mode === "custom" ? "Custom Start" : "Normal Start";
}

function stringToHex(value) {
  return [...value].map((char) => char.charCodeAt(0).toString(16).padStart(2, "0")).join("").toUpperCase();
}

function hexToString(hex) {
  const cleanHex = String(hex ?? "").trim();
  if (cleanHex.length % 2 !== 0 || /[^0-9a-fA-F]/.test(cleanHex)) throw new Error("Invalid hex payload.");
  let output = "";
  for (let index = 0; index < cleanHex.length; index += 2) {
    output += String.fromCharCode(Number.parseInt(cleanHex.slice(index, index + 2), 16));
  }
  return output;
}

function formatHexByte(value) {
  return (value & 0xff).toString(16).padStart(2, "0").toUpperCase();
}

function formatBool(value) {
  return value ? "ON" : "OFF";
}
